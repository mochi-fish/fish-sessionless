/** 种子 → 一整套词。dev-1 取第一项；别的种子随机取（槽和槽之间的字不重叠）。 */
export function lexiconFor (seed) {
  const rng = makeRng(`lexicon/${seed}`)
  const first = seed === 'dev-1'
  const out = {}
  const taken = [] // 已经选定的槽里的字（两个字以上的）
  const leaves = (v) => (typeof v === 'string' ? [v] : typeof v === 'number' ? [] : Array.isArray(v) ? v.flatMap(leaves) : Object.values(v).flatMap(leaves)).map((x) => String(x).replace(/[《》「」]/g, '')).filter((x) => x.length >= 2)
  const clash = (v) => leaves(v).some((x) => taken.some((t) => t.includes(x) || x.includes(t)))
  for (const [k, pool] of Object.entries(POOLS)) {
    if (first) { out[k] = pool[0]; continue }
    // 留出种子：槽和槽之间的字不许互相包含（免得群友叫「芒果」、零食也是芒果味）；实在避不开就用打乱后的第一个
    const order = rng.shuffle(pool)
    out[k] = order.find((v) => !clash(v)) ?? order[0]
    taken.push(...leaves(out[k]))
  }
  out.seed = seed
  const [m1, m2, m3] = out.members
  out.G1 = m1; out.G2 = m2; out.G3 = m3
  out.GUEST = out.guest
  return out
}
